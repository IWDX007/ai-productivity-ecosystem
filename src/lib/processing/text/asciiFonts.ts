const FONTS: Record<FontName, Font> = {
  block: BLOCK,
  shadow: SHADOW,
  slim: SLIM,
  outline: OUTLINE,
  digital: DIGITAL,
}

export function generateASCII(text: string, fontName: FontName = "block"): string {
  const font = FONTS[fontName]
  if (!text) return ""
  
  const rows: string[] = Array(font.height).fill("")
  const upper = text.toUpperCase()
  
  for (const ch of upper) {
    let glyph: string[]
    if (ch === " ") {
      glyph = font.space
    } else if (font.chars[ch]) {
      glyph = font.chars[ch]
    } else {
      glyph = font.space
    }
    for (let i = 0; i < font.height; i++) {
      rows[i] += glyph[i]
    }
  }
  
  return rows.join("\n")
}

